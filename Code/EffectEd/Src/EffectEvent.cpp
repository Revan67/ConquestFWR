IEffectEvent * EffectEvent::CreateCopy(IEffectAction * _newParent)
{
	EffectEvent * event = new EffectEvent();
	if(next)
		event->next = next->CreateCopy(_newParent);
	else
		event->next = NULL;
	strcpy(event->name,name);
	event->offSetTime = offSetTime;
	event->eventType = eventType;
	event->bFileDependant = bFileDependant;
	if(firstAction)
	{
		event->firstAction = firstAction->CreateCopy();
		IEffectAction * search = event->firstAction;
		while(search)
		{
			search->SetParent(this);
			search = search->GetNextAction();
		}
	}
	else
		event->firstAction = NULL;
	event->parent = _newParent;
	return event;
}

void EffectEvent::AddRef()
{
	++refCount;
}

void EffectEvent::RemoveRef()
{
	--refCount;
}

U32 EffectEvent::GetRef()
{
	return refCount;
}

S32 EffectEvent::GetIconXPos()
{
	if(parent)
		return parent->GetIconXPos()+iconXPos;
	return iconXPos;
}

S32 EffectEvent::GetIconYPos()
{
	if(parent)
		return parent->GetIconYPos()+iconYPos;
	return iconYPos;
}

void EffectEvent::SetDimentions(S32 newWidth, S32 newHeight)
{
	iconWidth = newWidth;
	iconHeight = newHeight;
}

bool EffectEvent::HitTest(S32 x, S32 y)
{
	if(x >= GetIconXPos() && x <= GetIconXPos()+iconWidth && y >= GetIconYPos() && y <= GetIconYPos()+iconHeight)
		return true;
	return false;
}

void EffectEvent::RealitveIconMove(S32 x, S32 y)
{
	iconXPos += x;
	iconYPos += y;
}

void EffectEvent::SetIconPos(S32 x, S32 y)
{
	iconXPos = x;
	iconYPos = y;
}

IEffectEvent * MakeEffectEvent()
{
	return new EffectEvent();
}

